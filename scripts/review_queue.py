#!/usr/bin/env python3
"""Generate review/queue.md from data/judgments.json (offline; no API). Internal working document, not a rendered page."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
load = lambda n: json.loads((ROOT / "data" / n).read_text())  # noqa: E731
repos = {r["id"]: r for r in load("repos.json")}
judg = load("judgments.json")
snip = load("snippets.json")
cand = {c["id"]: c for c in load("candidates.json")}
KIND = {"general": "Frameworks & Toolkits", "promo": "Promos & Demos", "explainer": "Explainers", "editing": "Editing", "shorts": "Short-form",
        "avatar": "Avatars", "story": "Story & Animation", "motion": "Motion Graphics", "craft": "Scriptwriting", "music": "Music Videos",
        "out_of_scope": "OUT OF SCOPE"}


def code(s, n=280):
    s = s.strip()[:n] + ("..." if len(s.strip()) > n else "")
    return "```\n" + s + "\n```"


def main():
    L = ["# Review queue", "",
         "Internal working document (not rendered into the published pages). Generated by `python3 scripts/review_queue.py` from `data/judgments.json`.",
         "Judgments are ours (TypeSafe Jev, see docs/methodology.md), not upstream's. Nothing here changes the data until a decision is recorded in `data/review_decisions.json`.",
         "Decision key: `accept` / `reject` / `showcase` / `remove`. Reply per row id.", ""]
    # A
    A = [(i, j["category_suggestion"]) for i, j in judg.items()
         if j["category_suggestion"]["choice"] != cand[i]["category_source"] and j["category_suggestion"]["confidence"] > 0.9]
    L += [f"## A. Category: model disagrees with upstream at confidence > 0.9 ({len(A)})", "",
          "Proposed action: keep upstream's category unless you accept the suggestion. Categories are never auto-changed.", "",
          "| id | upstream | suggested | conf | decision |", "|---|---|---|---:|---|"]
    for i, s in sorted(A, key=lambda x: -x[1]["confidence"]):
        L.append(f"| {i} | {KIND[cand[i]['category_source']]} | {KIND[s['choice']]} | {s['confidence']:.2f} | |")
    # B
    B = [(i, j["inclusion"], j["category_suggestion"]) for i, j in judg.items()
         if j["inclusion"]["makes_video"] < 0.5 or j["inclusion"]["agent_oriented"] < 0.5 or j["category_suggestion"]["choice"] == "out_of_scope"]
    L += ["", f"## B. Inclusion flags: makes_video < 0.5, agent_oriented < 0.5, or category out_of_scope ({len(B)})", "",
          "Expected: the craft carve-out repos (pre-production; upstream lists them by the maintainer's choice). Proposed action: keep, or mark `showcase` / `remove`.", "",
          "| id | upstream category | makes_video | agent_oriented | category says out_of_scope | entry_kind now | decision |", "|---|---|---:|---:|:-:|---|---|"]
    for i, inc, cs in sorted(B, key=lambda x: x[1]["makes_video"]):
        L.append(f"| {i} | {KIND[cand[i]['category_source']]} | {inc['makes_video']:.2f} | {inc['agent_oriented']:.2f} | {'yes' if cs['choice']=='out_of_scope' else ''} | {repos[i]['entry_kind']} | |")
    # C
    C = [i for i, j in judg.items() if not snip.get(i, {}).get("install") and j["install_choice"] and j["install_choice"]["choice"] != "none"]
    L += ["", f"## C. Install: extractor found nothing, model picked a candidate ({len(C)})", "",
          "Proposed action: `accept` if the shown candidate is the project's install step (it is a verbatim README string; accepting records it with the README link). Otherwise `reject`.", ""]
    for i in sorted(C):
        ic = judg[i]["install_choice"]
        cur = "(hand-nulled: extractor false positive)" if repos[i]["install"] is None and snip.get(i, {}).get("install") else ""
        L += [f"### {i}  (conf {ic['confidence']:.2f}, {ic['n_candidates']} candidates) {cur}", code(ic["candidate"]), "Decision: ", ""]
    # D
    D = [i for i, j in judg.items() if snip.get(i, {}).get("install") and j["install_choice"] and j["install_choice"]["choice"] == "none"]
    L += ["", f"## D. Install: extractor found a block, model says none of the candidates is an install ({len(D)})", "",
          "Proposed action: `keep` the extractor value unless it is not an install step (then `reject` -> install becomes null).", ""]
    for i in sorted(D):
        ex = snip[i]["install"]
        L += [f"### {i}  (model conf {judg[i]['install_choice']['confidence']:.2f}; current: {'null (hand override)' if repos[i]['install'] is None else 'kept'})", code(ex["command"]), "Decision: ", ""]
    (ROOT / "review").mkdir(exist_ok=True)
    (ROOT / "review/queue.md").write_text("\n".join(L) + "\n")
    print(f"A={len(A)} B={len(B)} C={len(C)} D={len(D)}")


if __name__ == "__main__":
    main()
